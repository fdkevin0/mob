// Command contracts emits the Go-owned JSON contract used by the local UI.
package main

import (
	"fmt"
	"reflect"
	"strings"

	"github.com/fdkevin0/mob/internal/agents"
	"github.com/fdkevin0/mob/internal/chat"
	"github.com/fdkevin0/mob/internal/configuration"
	"github.com/fdkevin0/mob/internal/plugins/cloudflare"
	"github.com/fdkevin0/mob/internal/plugins/email"
	"github.com/fdkevin0/mob/internal/plugins/telegram"
	"github.com/fdkevin0/mob/internal/plugins/wechatilink"
)

type definition struct {
	name  string
	value any
}

var definitions = []definition{
	{"Endpoint", email.Endpoint{}},
	{"EmailChannel", email.Channel{}},
	{"EmailConfig", email.Config{}},
	{"TelegramConfig", telegram.Config{}},
	{"CloudflareConfig", cloudflare.Config{}},
	{"WeChatILinkConfig", wechatilink.Config{}},
	{"Configs", configuration.Plugins{}},
	{"Config", configuration.Snapshot{}},
	{"SecretUpdate", configuration.SecretUpdate{}},
	{"Delivery", chat.Delivery{}},
	{"CommandSpec", chat.CommandSpec{}},
	{"Suggestion", chat.Suggestion{}},
	{"CommandRequest", chat.CommandRequest{}},
	{"Action", chat.Action{}},
	{"CommandResult", chat.CommandResult{}},
	{"ModelUsage", chat.ModelUsage{}},
	{"DayUsage", chat.DayUsage{}},
	{"TopConversation", chat.TopConversation{}},
	{"UsageReport", chat.UsageReport{}},
	{"UsageSummary", chat.UsageSummary{}},
	{"PlanEntry", chat.PlanEntry{}},
	{"Task", chat.Task{}},
	{"AgentApproval", agents.AgentApproval{}},
	{"AgentNode", agents.AgentNode{}},
}

func contract() string {
	names := map[reflect.Type]string{}
	for _, d := range definitions {
		names[reflect.TypeOf(d.value)] = d.name
	}
	var out strings.Builder
	out.WriteString("// Generated by go run ./cmd/contracts. Do not edit.\n")
	var kind func(reflect.Type) string
	kind = func(t reflect.Type) string {
		if name := names[t]; name != "" {
			return name
		}
		switch t.Kind() {
		case reflect.String:
			return "string"
		case reflect.Bool:
			return "boolean"
		case reflect.Int, reflect.Int64, reflect.Uint32, reflect.Float64:
			return "number"
		case reflect.Slice:
			return kind(t.Elem()) + "[]"
		case reflect.Pointer:
			return kind(t.Elem())
		default:
			panic("unsupported contract type: " + t.String())
		}
	}
	for _, d := range definitions {
		fmt.Fprintf(&out, "export type %s = {\n", d.name)
		// Embedded structs' fields are written in place, as encoding/json does.
		for _, f := range reflect.VisibleFields(reflect.TypeOf(d.value)) {
			tag := strings.Split(f.Tag.Get("json"), ",")
			if !f.IsExported() || f.Anonymous || tag[0] == "-" || tag[0] == "" {
				continue
			}
			optional := ""
			if len(tag) > 1 && tag[1] == "omitempty" {
				optional = "?"
			}
			fmt.Fprintf(&out, "  %s%s: %s;\n", tag[0], optional, kind(f.Type))
		}
		out.WriteString("};\n")
	}
	return out.String()
}
func main() { fmt.Print(contract()) }
